def load_translation_rules() -> list[tuple[str, str]]:
    """Возвращает активные правила из БД или встроенный набор при пустом справочнике."""
    try:
        from production.models import TestDataTranslation

        rows = list(
            TestDataTranslation.objects.filter(is_active=True)
            .order_by("-source")
            .values_list("source", "target")
        )
    except Exception:
        rows = []
    return rows or DEFAULT_TEST_DATA_TRANSLATIONS


def translate_test_data(
    text: str,
    rules: list[tuple[str, str]] | None = None,
) -> str:
    """Переводит известные фрагменты ``testData``; неизвестные оставляет без изменений."""
    if not text:
        return text
    rules = rules or load_translation_rules()
    for source, target in sorted(rules, key=lambda item: len(item[0]), reverse=True):
        text = text.replace(source, target)
    return text